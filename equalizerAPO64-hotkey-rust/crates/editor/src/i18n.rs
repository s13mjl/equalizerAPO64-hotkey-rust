use std::sync::OnceLock;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Language { English, German, French, Chinese }

static LANGUAGE: OnceLock<Language> = OnceLock::new();

pub fn set_language(language: Language) { let _ = LANGUAGE.set(language); }

pub fn language() -> Language { *LANGUAGE.get().unwrap_or(&Language::English) }

pub fn language_code(language: Language) -> &'static str {
    match language {
        Language::English => "en",
        Language::German => "de",
        Language::French => "fr",
        Language::Chinese => "zh",
    }
}

pub fn from_code(code: &str) -> Language {
    match code.split(['_', '-']).next().unwrap_or("") {
        "de" => Language::German,
        "fr" => Language::French,
        "zh" => Language::Chinese,
        _ => Language::English,
    }
}

pub fn tr(text: &str) -> String {
    let map: &[(&str, &str)] = match language() {
        Language::English => return text.to_string(),
        Language::German => GERMAN,
        Language::French => FRENCH,
        Language::Chinese => CHINESE,
    };
    map.iter().find(|(source, _)| *source == text).map(|(_, translation)| (*translation).to_string()).unwrap_or_else(|| text.to_string())
}

