pub fn native_name(language: Language) -> &'static str {
    match language {
        Language::English => "English",
        Language::German => "Deutsch",
        Language::French => "Français",
        Language::Chinese => "中文",
    }
}

/// The C++ editor falls back to English when the system language has no
/// translation.
pub fn system_language() -> Language {
    use windows::Win32::Globalization::GetUserDefaultUILanguage;
    let id = unsafe { GetUserDefaultUILanguage() } & 0x3ff;
    match id {
        0x07 => Language::German,
        0x0c => Language::French,
        0x04 => Language::Chinese,
        _ => Language::English,
    }
}

/// Substitutes `%0`, `%1`, ... in a translated string, mirroring Qt's
/// `QString::arg()`.
pub fn tr_arg(source: &str, args: &[&str]) -> String {
    let mut text = tr(source);
    for (index, arg) in args.iter().enumerate() {
        text = text.replace(&format!("%{index}"), arg);
    }
    text
}
